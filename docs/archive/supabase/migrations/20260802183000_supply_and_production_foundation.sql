create or replace function public.set_record_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := timezone('utc', now());
  return new;
end;
$$;

create or replace function private.current_user_is_active()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.user_profiles as profile
    where profile.id = (select auth.uid())
      and profile.is_active
  );
$$;

create or replace function private.current_user_has_any_role(
  required_roles public.app_role[]
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.user_profiles as profile
    where profile.id = (select auth.uid())
      and profile.is_active
      and profile.role = any(required_roles)
  );
$$;

revoke execute on function private.current_user_is_active()
from public, anon, authenticated, service_role;

revoke execute on function private.current_user_has_any_role(public.app_role[])
from public, anon, authenticated, service_role;

create table public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null,
  description text,
  is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint products_name_key unique (name),
  constraint products_slug_key unique (slug)
);

create table public.product_variants (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products (id) on delete restrict,
  sku text not null,
  variant_name text not null,
  flavor text not null default 'Classic',
  pack_size_grams integer not null,
  packaging_type text not null default 'Jar',
  is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint product_variants_sku_key unique (sku),
  constraint product_variants_pack_size_grams_check
    check (pack_size_grams > 0)
);

create table public.materials (
  id bigint generated by default as identity primary key,
  code text not null,
  name text not null,
  kind public.material_kind not null,
  unit_of_measure text not null,
  description text,
  is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint materials_code_key unique (code)
);

create table public.suppliers (
  id bigint generated by default as identity primary key,
  supplier_name text not null,
  supplier_kind public.supplier_kind not null default 'mixed',
  contact_name text,
  phone text,
  email text,
  notes text,
  is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create unique index suppliers_name_lower_key
  on public.suppliers (lower(supplier_name));

create table public.purchases (
  id bigint generated by default as identity primary key,
  supplier_id bigint not null references public.suppliers (id) on delete restrict,
  purchase_reference text,
  purchased_at timestamptz not null default timezone('utc', now()),
  status public.purchase_status not null default 'draft',
  total_amount numeric(14, 2) not null default 0,
  notes text,
  created_by uuid,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint purchases_total_amount_check
    check (total_amount >= 0)
);

create table public.purchase_items (
  id bigint generated by default as identity primary key,
  purchase_id bigint not null references public.purchases (id) on delete cascade,
  line_number integer not null,
  material_id bigint not null references public.materials (id) on delete restrict,
  lot_code text not null,
  quantity numeric(14, 3) not null,
  unit_cost numeric(14, 2) not null,
  line_total numeric(14, 2) generated always as (
    round(quantity * unit_cost, 2)
  ) stored,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint purchase_items_purchase_line_key unique (purchase_id, line_number),
  constraint purchase_items_lot_code_key unique (lot_code),
  constraint purchase_items_quantity_check check (quantity > 0),
  constraint purchase_items_unit_cost_check check (unit_cost >= 0)
);

create table public.inventory_lots (
  id bigint generated by default as identity primary key,
  material_id bigint not null references public.materials (id) on delete restrict,
  supplier_id bigint not null references public.suppliers (id) on delete restrict,
  source_purchase_item_id bigint not null
    references public.purchase_items (id) on delete restrict,
  lot_code text not null,
  quantity_received numeric(14, 3) not null,
  quantity_remaining numeric(14, 3) not null,
  unit_cost numeric(14, 2) not null,
  received_at timestamptz not null default timezone('utc', now()),
  status public.inventory_lot_status not null default 'open',
  notes text,
  created_by uuid,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint inventory_lots_source_purchase_item_id_key
    unique (source_purchase_item_id),
  constraint inventory_lots_lot_code_key unique (lot_code),
  constraint inventory_lots_quantity_received_check check (quantity_received > 0),
  constraint inventory_lots_quantity_remaining_check
    check (
      quantity_remaining >= 0
      and quantity_remaining <= quantity_received
    ),
  constraint inventory_lots_unit_cost_check check (unit_cost >= 0)
);

create table public.production_batches (
  id bigint generated by default as identity primary key,
  batch_code text not null,
  variant_id bigint not null
    references public.product_variants (id) on delete restrict,
  started_at timestamptz not null default timezone('utc', now()),
  completed_at timestamptz not null default timezone('utc', now()),
  status public.production_batch_status not null default 'draft',
  total_input_cost numeric(14, 2) not null default 0,
  total_output_quantity integer not null default 0,
  output_unit_cost numeric(14, 2) not null default 0,
  notes text,
  created_by uuid,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint production_batches_batch_code_key unique (batch_code),
  constraint production_batches_total_input_cost_check
    check (total_input_cost >= 0),
  constraint production_batches_total_output_quantity_check
    check (total_output_quantity >= 0),
  constraint production_batches_output_unit_cost_check
    check (output_unit_cost >= 0),
  constraint production_batches_completed_after_started_check
    check (completed_at >= started_at)
);

create table public.production_inputs (
  id bigint generated by default as identity primary key,
  production_batch_id bigint not null
    references public.production_batches (id) on delete cascade,
  line_number integer not null,
  inventory_lot_id bigint not null
    references public.inventory_lots (id) on delete restrict,
  material_id bigint not null references public.materials (id) on delete restrict,
  quantity_consumed numeric(14, 3) not null,
  unit_cost numeric(14, 2) not null,
  total_cost numeric(14, 2) generated always as (
    round(quantity_consumed * unit_cost, 2)
  ) stored,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint production_inputs_batch_line_key
    unique (production_batch_id, line_number),
  constraint production_inputs_quantity_consumed_check
    check (quantity_consumed > 0),
  constraint production_inputs_unit_cost_check check (unit_cost >= 0)
);

create table public.production_outputs (
  id bigint generated by default as identity primary key,
  production_batch_id bigint not null
    references public.production_batches (id) on delete cascade,
  line_number integer not null,
  variant_id bigint not null
    references public.product_variants (id) on delete restrict,
  quantity_produced integer not null,
  quantity_remaining integer not null,
  unit_cost numeric(14, 2) not null,
  total_cost numeric(14, 2) generated always as (
    round(quantity_produced * unit_cost, 2)
  ) stored,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint production_outputs_batch_line_key
    unique (production_batch_id, line_number),
  constraint production_outputs_quantity_produced_check
    check (quantity_produced > 0),
  constraint production_outputs_quantity_remaining_check
    check (
      quantity_remaining >= 0
      and quantity_remaining <= quantity_produced
    ),
  constraint production_outputs_unit_cost_check check (unit_cost >= 0)
);

