create type public.stock_issue_status as enum (
  'draft',
  'issued',
  'voided'
);

create type public.retailer_stock_movement_type as enum (
  'issue',
  'reconciliation_sale',
  'return_to_warehouse',
  'damage',
  'adjustment_in',
  'adjustment_out',
  'transfer_in',
  'transfer_out'
);

create table public.retailers (
  id bigint generated by default as identity primary key,
  retailer_name text not null,
  contact_name text,
  phone text,
  email text,
  delivery_location text,
  notes text,
  is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create unique index retailers_name_lower_key
  on public.retailers (lower(retailer_name));

create index retailers_is_active_idx
  on public.retailers (is_active);

create table public.stock_issues (
  id bigint generated by default as identity primary key,
  retailer_id bigint not null references public.retailers (id) on delete restrict,
  issue_reference text,
  issued_at timestamptz not null default timezone('utc', now()),
  status public.stock_issue_status not null default 'draft',
  total_quantity integer not null default 0,
  total_cost numeric(14, 2) not null default 0,
  notes text,
  created_by uuid,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint stock_issues_total_quantity_check
    check (total_quantity >= 0),
  constraint stock_issues_total_cost_check
    check (total_cost >= 0)
);

create index stock_issues_retailer_id_idx
  on public.stock_issues (retailer_id);

create index stock_issues_retailer_issued_at_idx
  on public.stock_issues (retailer_id, issued_at desc);

create index stock_issues_status_idx
  on public.stock_issues (status);

create table public.stock_issue_items (
  id bigint generated by default as identity primary key,
  stock_issue_id bigint not null
    references public.stock_issues (id) on delete cascade,
  line_number integer not null,
  production_output_id bigint not null
    references public.production_outputs (id) on delete restrict,
  production_batch_id bigint not null
    references public.production_batches (id) on delete restrict,
  variant_id bigint not null
    references public.product_variants (id) on delete restrict,
  quantity_issued integer not null,
  unit_cost numeric(14, 2) not null,
  total_cost numeric(14, 2) generated always as (
    round(quantity_issued * unit_cost, 2)
  ) stored,
  notes text,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint stock_issue_items_issue_line_key unique (stock_issue_id, line_number),
  constraint stock_issue_items_quantity_issued_check check (quantity_issued > 0),
  constraint stock_issue_items_unit_cost_check check (unit_cost >= 0)
);

create index stock_issue_items_stock_issue_id_idx
  on public.stock_issue_items (stock_issue_id);

create index stock_issue_items_production_output_id_idx
  on public.stock_issue_items (production_output_id);

create index stock_issue_items_production_batch_id_idx
  on public.stock_issue_items (production_batch_id);

create index stock_issue_items_variant_id_idx
  on public.stock_issue_items (variant_id);

create table public.retailer_stock_ledgers (
  id bigint generated by default as identity primary key,
  retailer_id bigint not null references public.retailers (id) on delete restrict,
  product_variant_id bigint not null
    references public.product_variants (id) on delete restrict,
  production_batch_id bigint not null
    references public.production_batches (id) on delete restrict,
  production_output_id bigint
    references public.production_outputs (id) on delete restrict,
  stock_issue_id bigint references public.stock_issues (id) on delete restrict,
  stock_issue_item_id bigint
    references public.stock_issue_items (id) on delete restrict,
  movement_type public.retailer_stock_movement_type not null,
  quantity_delta integer not null,
  unit_cost numeric(14, 2) not null,
  moved_at timestamptz not null default timezone('utc', now()),
  notes text,
  created_by uuid,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint retailer_stock_ledgers_quantity_delta_check check (quantity_delta <> 0),
  constraint retailer_stock_ledgers_unit_cost_check check (unit_cost >= 0)
);

create index retailer_stock_ledgers_retailer_id_idx
