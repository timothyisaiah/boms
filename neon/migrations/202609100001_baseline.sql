create or replace view public.retailer_outstanding_balances
with (security_invoker = true)
as
with issue_totals as (
  select
    ledger.retailer_id,
    coalesce(
      sum(
        case
          when ledger.movement_type = 'issue' then ledger.quantity_delta
          else 0
        end
      ),
      0
    )::integer as issued_quantity
  from public.retailer_stock_ledgers as ledger
  group by ledger.retailer_id
),
reconciliation_totals as (
  select
    reconciliation.retailer_id,
    count(distinct reconciliation.id)::integer as reconciliation_count,
    max(reconciliation.reconciled_at) as last_reconciled_at,
    coalesce(sum(item.quantity_sold), 0)::integer as sold_quantity,
    coalesce(sum(item.quantity_returned), 0)::integer as returned_quantity,
    coalesce(sum(item.quantity_damaged), 0)::integer as damaged_quantity,
    coalesce(sum(item.sales_value), 0)::numeric(14, 2) as recognized_sales_value,
    coalesce(sum(item.cogs_value), 0)::numeric(14, 2) as cost_of_goods_sold
  from public.reconciliations as reconciliation
  join public.reconciliation_items as item
    on item.reconciliation_id = reconciliation.id
  group by reconciliation.retailer_id
),
open_totals as (
  select
    open_balance.retailer_id,
    coalesce(sum(open_balance.quantity_open), 0)::integer as remaining_quantity
  from public.retailer_issue_open_balances as open_balance
  group by open_balance.retailer_id
),
remittance_totals as (
  select
    remittance.retailer_id,
    count(*)::integer as remittance_count,
    max(remittance.received_at) as last_remitted_at,
    coalesce(sum(remittance.amount), 0)::numeric(14, 2) as remitted_amount
  from public.remittances as remittance
  group by remittance.retailer_id
)
select
  retailer.id as retailer_id,
  retailer.retailer_name,
  retailer.delivery_location,
  coalesce(issue_totals.issued_quantity, 0) as issued_quantity,
  coalesce(reconciliation_totals.reconciliation_count, 0) as reconciliation_count,
  coalesce(remittance_totals.remittance_count, 0) as remittance_count,
  coalesce(reconciliation_totals.sold_quantity, 0) as sold_quantity,
  coalesce(reconciliation_totals.returned_quantity, 0) as returned_quantity,
  coalesce(reconciliation_totals.damaged_quantity, 0) as damaged_quantity,
  coalesce(open_totals.remaining_quantity, 0) as remaining_quantity,
  coalesce(reconciliation_totals.recognized_sales_value, 0)::numeric(14, 2)
    as recognized_sales_value,
  coalesce(reconciliation_totals.cost_of_goods_sold, 0)::numeric(14, 2)
    as cost_of_goods_sold,
  round(
    coalesce(reconciliation_totals.recognized_sales_value, 0)
    - coalesce(reconciliation_totals.cost_of_goods_sold, 0),
    2
  ) as gross_profit,
  coalesce(remittance_totals.remitted_amount, 0)::numeric(14, 2)
    as remitted_amount,
  round(
    coalesce(reconciliation_totals.recognized_sales_value, 0)
    - coalesce(remittance_totals.remitted_amount, 0),
    2
  ) as outstanding_amount,
  reconciliation_totals.last_reconciled_at,
  remittance_totals.last_remitted_at
from public.retailers as retailer
left join issue_totals
  on issue_totals.retailer_id = retailer.id
left join reconciliation_totals
  on reconciliation_totals.retailer_id = retailer.id
left join open_totals
  on open_totals.retailer_id = retailer.id
left join remittance_totals
  on remittance_totals.retailer_id = retailer.id
where retailer.is_active
order by outstanding_amount desc, retailer.retailer_name asc;

create or replace view public.finance_profit_summary
with (security_invoker = true)
as
with retailer_totals as (
  select
    coalesce(sum(balance.issued_quantity), 0)::integer as issued_quantity,
    coalesce(sum(balance.sold_quantity), 0)::integer as sold_quantity,
    coalesce(sum(balance.returned_quantity), 0)::integer as returned_quantity,
    coalesce(sum(balance.damaged_quantity), 0)::integer as damaged_quantity,
    coalesce(sum(balance.remaining_quantity), 0)::integer as remaining_quantity,
    coalesce(sum(balance.recognized_sales_value), 0)::numeric(14, 2)
      as recognized_sales_value,
    coalesce(sum(balance.cost_of_goods_sold), 0)::numeric(14, 2)
      as cost_of_goods_sold,
    coalesce(sum(balance.gross_profit), 0)::numeric(14, 2) as gross_profit,
    coalesce(sum(balance.remitted_amount), 0)::numeric(14, 2) as remitted_amount,
    coalesce(sum(balance.outstanding_amount), 0)::numeric(14, 2)
      as outstanding_amount,
    count(*) filter (
      where balance.issued_quantity > 0
        or balance.sold_quantity > 0
        or balance.remaining_quantity > 0
    )::integer as active_retailers
  from public.retailer_outstanding_balances as balance
),
expense_totals as (
  select
    count(*)::integer as expense_count,
    coalesce(sum(expense.amount), 0)::numeric(14, 2) as operating_expenses
  from public.expenses as expense
)
select
  retailer_totals.active_retailers,
  retailer_totals.issued_quantity,
  retailer_totals.sold_quantity,
  retailer_totals.returned_quantity,
  retailer_totals.damaged_quantity,
  retailer_totals.remaining_quantity,
  retailer_totals.recognized_sales_value,
  retailer_totals.cost_of_goods_sold,
  retailer_totals.gross_profit,
  expense_totals.expense_count,
  expense_totals.operating_expenses,
  round(
    retailer_totals.gross_profit - expense_totals.operating_expenses,
    2
  ) as net_profit,
  retailer_totals.remitted_amount,
  retailer_totals.outstanding_amount
from retailer_totals
cross join expense_totals;

create or replace function public.record_purchase(
  p_supplier_id bigint,
  p_purchased_at timestamptz,
  p_purchase_reference text,
  p_notes text,
  p_items jsonb
)
returns bigint
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_actor_id uuid;
  v_purchase_id bigint;
  v_item jsonb;
  v_item_id bigint;
  v_line_number integer := 0;
  v_material_id bigint;
  v_quantity numeric(14, 3);
  v_unit_cost numeric(14, 2);
  v_lot_code text;
  v_line_total numeric(14, 2);
  v_purchase_total numeric(14, 2) := 0;
begin
  v_actor_id := nullif(current_setting('boms.actor_id', true), '')::uuid;

  if v_actor_id is null then
    raise exception 'Authentication is required to record purchases.';
  end if;


  if p_items is null
    or jsonb_typeof(p_items) <> 'array'
    or jsonb_array_length(p_items) = 0
  then
    raise exception 'At least one purchase line item is required.';
  end if;

  if not exists (
    select 1
    from public.suppliers as supplier
    where supplier.id = p_supplier_id
      and supplier.is_active
  ) then
    raise exception 'The selected supplier is not available.';
  end if;

  insert into public.purchases (
    supplier_id,
    purchase_reference,
    purchased_at,
    status,
    total_amount,
    notes,
    created_by
  )
  values (
    p_supplier_id,
    nullif(btrim(p_purchase_reference), ''),
    coalesce(p_purchased_at, timezone('utc', now())),
    'received',
    0,
    nullif(btrim(p_notes), ''),
    v_actor_id
  )
  returning id into v_purchase_id;

  for v_item in
    select value
    from jsonb_array_elements(p_items)
  loop
    v_line_number := v_line_number + 1;
    v_material_id := nullif(btrim(v_item ->> 'material_id'), '')::bigint;
    v_quantity := nullif(btrim(v_item ->> 'quantity'), '')::numeric(14, 3);
    v_unit_cost := nullif(btrim(v_item ->> 'unit_cost'), '')::numeric(14, 2);

    if not exists (
      select 1
      from public.materials as material
      where material.id = v_material_id
        and material.is_active
    ) then
      raise exception 'A purchase line references an unavailable material.';
    end if;

    if v_quantity is null or v_quantity <= 0 then
      raise exception 'Purchase quantities must be greater than zero.';
    end if;

    if v_unit_cost is null or v_unit_cost < 0 then
      raise exception 'Purchase unit cost must be zero or greater.';
    end if;

    insert into public.purchase_items (
      purchase_id,
      line_number,
      material_id,
      lot_code,
      quantity,
      unit_cost
    )
    values (
      v_purchase_id,
      v_line_number,
      v_material_id,
      coalesce(
        nullif(btrim(v_item ->> 'lot_code'), ''),
        format('LOT-PUR-%s-%s', v_purchase_id, v_line_number)
      ),
      v_quantity,
      v_unit_cost
    )
    returning
      id,
      lot_code,
      round(quantity * unit_cost, 2)
    into
      v_item_id,
      v_lot_code,
      v_line_total;

    insert into public.inventory_lots (
      material_id,
      supplier_id,
      source_purchase_item_id,
      lot_code,
      quantity_received,
      quantity_remaining,
      unit_cost,
      received_at,
      status,
      created_by
    )
    values (
      v_material_id,
      p_supplier_id,
      v_item_id,
      v_lot_code,
      v_quantity,
      v_quantity,
      v_unit_cost,
      coalesce(p_purchased_at, timezone('utc', now())),
      'open',
      v_actor_id
    );

    v_purchase_total := v_purchase_total + v_line_total;
  end loop;

  update public.purchases
  set total_amount = v_purchase_total
  where id = v_purchase_id;

  return v_purchase_id;
end;
$$;


create or replace function public.record_production_batch(
  p_variant_id bigint,
  p_batch_code text,
  p_started_at timestamptz,
  p_notes text,
  p_output_quantity integer,
  p_inputs jsonb
)
returns bigint
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_actor_id uuid;
  v_batch_id bigint;
  v_input jsonb;
  v_line_number integer := 0;
  v_inventory_lot_id bigint;
  v_material_id bigint;
  v_quantity_consumed numeric(14, 3);
  v_quantity_remaining numeric(14, 3);
  v_unit_cost numeric(14, 2);
  v_next_remaining numeric(14, 3);
  v_total_input_cost numeric(14, 2) := 0;
  v_output_unit_cost numeric(14, 2);
begin
  v_actor_id := nullif(current_setting('boms.actor_id', true), '')::uuid;

  if v_actor_id is null then
    raise exception 'Authentication is required to create production batches.';
  end if;


  if nullif(btrim(p_batch_code), '') is null then
    raise exception 'A batch code is required.';
  end if;

  if p_output_quantity is null or p_output_quantity <= 0 then
    raise exception 'Output quantity must be greater than zero.';
  end if;

  if p_inputs is null
    or jsonb_typeof(p_inputs) <> 'array'
    or jsonb_array_length(p_inputs) = 0
  then
    raise exception 'At least one production input is required.';
  end if;

  if not exists (
    select 1
    from public.product_variants as variant
    where variant.id = p_variant_id
      and variant.is_active
  ) then
    raise exception 'The selected product variant is not available.';
  end if;

  insert into public.production_batches (
    batch_code,
    variant_id,
    started_at,
    completed_at,
    status,
    notes,
    created_by
  )
  values (
    btrim(p_batch_code),
    p_variant_id,
    coalesce(p_started_at, timezone('utc', now())),
    coalesce(p_started_at, timezone('utc', now())),
    'completed'::public.production_batch_status,
    nullif(btrim(p_notes), ''),
    v_actor_id
  )
  returning id into v_batch_id;

  for v_input in
    select value
    from jsonb_array_elements(p_inputs)
  loop
    v_line_number := v_line_number + 1;
    v_inventory_lot_id := nullif(
      btrim(v_input ->> 'inventory_lot_id'),
      ''
    )::bigint;
    v_quantity_consumed := nullif(
      btrim(v_input ->> 'quantity'),
      ''
    )::numeric(14, 3);

    if v_quantity_consumed is null or v_quantity_consumed <= 0 then
      raise exception 'Production input quantities must be greater than zero.';
    end if;

    select
      lot.material_id,
      lot.quantity_remaining,
      lot.unit_cost
    into
      v_material_id,
      v_quantity_remaining,
      v_unit_cost
    from public.inventory_lots as lot
    where lot.id = v_inventory_lot_id
      and lot.status = 'open'::public.inventory_lot_status
    for update;

    if not found then
      raise exception 'A selected inventory lot is no longer available.';
    end if;

    if v_quantity_consumed > v_quantity_remaining then
      raise exception 'Cannot consume more material than the lot currently holds.';
    end if;

    v_next_remaining := v_quantity_remaining - v_quantity_consumed;

    update public.inventory_lots
    set
      quantity_remaining = v_next_remaining,
      status = case
        when v_next_remaining = 0
          then 'depleted'::public.inventory_lot_status
        else 'open'::public.inventory_lot_status
      end
    where id = v_inventory_lot_id;

    insert into public.production_inputs (
      production_batch_id,
      line_number,
      inventory_lot_id,
      material_id,
      quantity_consumed,
      unit_cost
    )
    values (
      v_batch_id,
      v_line_number,
      v_inventory_lot_id,
      v_material_id,
      v_quantity_consumed,
      v_unit_cost
    );

    v_total_input_cost := v_total_input_cost
      + round(v_quantity_consumed * v_unit_cost, 2);
  end loop;

  v_output_unit_cost := round(
    v_total_input_cost / p_output_quantity,
    2
  );

  insert into public.production_outputs (
    production_batch_id,
    line_number,
    variant_id,
    quantity_produced,
    quantity_remaining,
    unit_cost
  )
  values (
    v_batch_id,
    1,
    p_variant_id,
    p_output_quantity,
    p_output_quantity,
    v_output_unit_cost
  );

  update public.production_batches
  set
    total_input_cost = v_total_input_cost,
    total_output_quantity = p_output_quantity,
    output_unit_cost = v_output_unit_cost
  where id = v_batch_id;

  return v_batch_id;
end;
$$;
create or replace function public.record_stock_issue(
