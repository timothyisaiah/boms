    round(p_amount::numeric, 2),
    nullif(btrim(p_vendor_name), ''),
    nullif(btrim(p_expense_reference), ''),
    nullif(btrim(p_notes), ''),
    v_actor_id
  )
  returning id into v_expense_id;

  return v_expense_id;
end;
