  balance.production_output_id,
  balance.production_batch_id,
  batch.batch_code,
  balance.variant_id,
  variant.sku,
  variant.variant_name,
  issue_item.quantity_issued as original_quantity_issued,
  balance.quantity_open,
  issue_item.unit_cost,
